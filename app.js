function draft(){
  const g=STATE.game;
  const completed=g.assignments.length, total=completed+g.remaining.length;
  if(!g.remaining.length)return result();
  const left=g.revealing?(g.tempLeft||g.left):g.left;
  const right=g.revealing?(g.tempRight||g.right):g.right;
  return `
  <div class="progress-wrap"><div class="progress-top"><span>${completed} / ${total}</span><span>${g.skips} ${t("skipsLeft")}</span></div><div class="progress"><div style="width:${completed/total*100}%"></div></div></div>
  <div class="section-head"><div><div class="eyebrow">${t(STATE.selectedMode)}</div><h2>${g.revealing?t("revealing"):t("chooseOne")}</h2></div><button class="ghost" onclick="skipRound()" ${g.revealing?'disabled':''}>${t("skip")} ↻</button></div>
  <div class="duel">${left?charCard(left,"left",g.revealing):""}<div class="vs">${g.revealing?"⋯":"VS"}</div>${right?charCard(right,"right",g.revealing):""}</div>
  <div class="section-head"><div><h3>${t("remaining")}</h3></div></div>
  <div class="chips">${g.remaining.map(x=>`<span class="chip">${esc(x)}</span>`).join("")}</div>`;
}
