function pkPool(player){
  const pk=STATE.pk;
  const ids=pk.shared?[pk.p1.seriesId]:[player===1?pk.p1.seriesId:pk.p2.seriesId];
  return applyGenderFilter(ids.flatMap(id=>getSeries(id).chars)).filter(c=>!pk.used.has(c.id));
}
function drawPKPair(){
  const pool=pkPool(STATE.pk.turn);
  if(pool.length<2){STATE.pk.pair=pool;STATE.pk.revealing=false;return}
  STATE.pk.finalPair=shuffle(pool).slice(0,2);
  STATE.pk.revealing=true;
  let ticks=0;
  if(STATE.pk.timer) clearInterval(STATE.pk.timer);
  STATE.pk.timer=setInterval(()=>{
    const temp=shuffle(pool).slice(0,2);
    STATE.pk.pair=temp;
    ticks++;
    render();
    if(ticks>=12){
      clearInterval(STATE.pk.timer);
      STATE.pk.pair=STATE.pk.finalPair;
      STATE.pk.revealing=false;
      render();
    }
  },85);
}
