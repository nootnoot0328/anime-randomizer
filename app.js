async function startQuickReveal(){
  const q=STATE.quickReveal;
  for(let i=0;i<q.traits.length;i++){
    q.index=i;
    q.current=q.traits[i];
    let ticks=0;
    await new Promise(resolve=>{
      const timer=setInterval(()=>{
        q.currentDisplay=pick(q.pool);
        ticks++;
        render();
        if(ticks>=10){
          clearInterval(timer);
          const finalChar=pick(q.pool);
          q.currentDisplay=finalChar;
          q.assignments.push({trait:q.current,character:finalChar});
          render();
          setTimeout(resolve,350);
        }
      },80);
    });
  }
  STATE.game={kind:"quick",pool:q.pool,remaining:[],assignments:q.assignments,skips:0};
  STATE.quickReveal=null;
  setScreen("result","quickreveal");
}
