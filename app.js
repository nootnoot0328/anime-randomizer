async function runImageQueue(){
  if(STATE.imageFetchBusy) return;
  STATE.imageFetchBusy=true;
  while(STATE.imageFetchQueue.length){
    const c=STATE.imageFetchQueue.shift();
    const key=imageCacheKey(c);
    if(STATE.imageCache[key]) continue;
    try{
      const q=encodeURIComponent(c.name);
      const r=await fetch(`https://api.jikan.moe/v4/characters?q=${q}&limit=5`);
      if(!r.ok) throw new Error(`HTTP ${r.status}`);
      const data=await r.json();
      const rows=(data.data||[]);
      let hit=rows.find(x=>{
        const anime=(x.anime||[]).map(a=>a.anime?.title||"").join(" ").toLowerCase();
        return anime.includes(c.series.toLowerCase());
      }) || rows[0];
      const url=hit?.images?.jpg?.image_url || hit?.images?.webp?.image_url || null;
      if(url){
        STATE.imageCache[key]=url;
        localStorage.setItem("af_image_cache",JSON.stringify(STATE.imageCache));
        if(
          (STATE.screen==="draft" && (STATE.game?.left?.id===c.id || STATE.game?.right?.id===c.id)) ||
          (STATE.screen==="pk" && STATE.pk?.pair?.some(x=>x.id===c.id)) ||
          STATE.screen==="setup" || STATE.screen==="home"
        ) render();
      }
    }catch(e){
      console.warn("Image lookup failed for",c.name,e);
    }
    // Jikan is rate-limited; stay polite.
    await new Promise(r=>setTimeout(r,450));
  }
  STATE.imageFetchBusy=false;
}

