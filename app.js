function openDB(){
  return new Promise((resolve,reject)=>{
    const req=indexedDB.open("AnimeFusionDB",1);
    req.onupgradeneeded=()=>{req.result.createObjectStore("state")};
    req.onsuccess=()=>resolve(req.result);req.onerror=()=>reject(req.error);
  });
}
